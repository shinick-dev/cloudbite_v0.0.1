// Import the user's authored STA synthesis and held-out questions, never the licensed raw corpus.
// node tools/import-sta-knowledge.mjs --source <pro-bably-checkout> [--check]
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
const source = process.argv[process.argv.indexOf('--source') + 1];
if (!process.argv.includes('--source') || !source) throw Error('--source is required');
const root = path.resolve(import.meta.dirname, '..');
const raw = fs.readFileSync(path.join(source, 'data/experts/primetime-sta.json'));
const d = JSON.parse(raw);
if (d.expert_id !== 'probably-primetime-sta' || d.cards.length !== 50 || d.sources.length !== 120) throw Error('Unexpected source pack; review before importing');
const revision = execFileSync('git', ['-C', source, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
const pack = { expertId: d.expert_id, version: d.knowledge_version, instructions: d.instructions,
  cards: d.cards, sources: d.sources, roles: d.roles, limitations: d.limitations,
  generalCards: d.general_cards, generalChecklist: d.general_checklist,
  provenance: { repository: 'Shinick-Han/pro-bably', revision, path: 'data/experts/primetime-sta.json',
    sha256: createHash('sha256').update(raw).digest('hex'),
    cardsSha256: createHash('sha256').update(JSON.stringify(d.cards)).digest('hex'),
    sourcesSha256: createHash('sha256').update(JSON.stringify(d.sources)).digest('hex'),
    basis: 'Project-authored instructions and Korean syntheses with source metadata; no upstream full text or licensed corpus included.',
    curationRecords: d.provenance.curation_records, distinctSourceUrls: d.provenance.distinct_source_urls } };
const generated = '// Generated by tools/import-sta-knowledge.mjs from the user-authored Pro-bably STA pack.\n'
  + 'import type { StaKnowledgePack } from "./cloudbite-sta";\n'
  + 'export const STA_PACK: StaKnowledgePack = ' + JSON.stringify(pack, null, 2) + ';\n';
const evaluations = fs.readFileSync(path.join(source, 'research/eda-sta/evaluation-cases.jsonl'), 'utf8').replace(/\r\n/g, '\n');
if (evaluations.trim().split('\n').length !== 24) throw Error('Expected 24 held-out cases');
for (const [file, content] of [['src/cloudbite-sta-data.ts', generated], ['test/fixtures/sta-evaluation-cases.jsonl', evaluations]]) {
  const target = path.join(root, file);
  if (process.argv.includes('--check')) { if (fs.readFileSync(target, 'utf8') !== content) throw Error(file + ' differs from source'); }
  else { fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, content); }
}
console.log('STA pack: 50 authored cards, 120 source records, 8 checklists; 24 evaluation cases kept under test/ only.');
